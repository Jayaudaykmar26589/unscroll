"""Run the seeded real-data tracing on a Kaggle GPU (private datasets + notebook).

  python scripts/kaggle_run.py stage        # build kaggle/stage/{slices,weights,code,kernel}
  python scripts/kaggle_run.py push-data    # create/version three PRIVATE datasets
  python scripts/kaggle_run.py push-kernel  # push the private T4 GPU notebook (starts a run)
  python scripts/kaggle_run.py status
  python scripts/kaggle_run.py fetch        # download curves into reports/seeded_eval/

Crop job (one seed, many slices, ~1.3 GB instead of full slices):
  python scripts/make_crop.py --seed-id ID --n 100
  python scripts/kaggle_run.py stage --crop ID; ... push-data --crop ID --only crop code;
  ... push-kernel --crop ID; ... status --crop ID; ... fetch --crop ID
  (fetch writes reports/flatten/curves_<ID>_kaggle in volume coordinates)

Needs Kaggle API credentials (~/.kaggle/kaggle.json or KAGGLE_USERNAME/KAGGLE_KEY).
Large files are hard-linked into the stage, not copied. The notebook runs the
unchanged `scripts/seeded_eval.py trace` and copies results to /kaggle/working
every few minutes, so a timeout keeps finished seeds. Scoring stays local.
"""
