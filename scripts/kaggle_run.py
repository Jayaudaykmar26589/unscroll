def kaggle(*args, check=True):
    exe = Path(sys.executable).with_name("kaggle.exe")
    cmd = [str(exe) if exe.exists() else "kaggle", *args]
    print("+", " ".join(cmd), flush=True)
    return subprocess.run(cmd, check=check, text=True, capture_output=False)


def username():
    """Kaggle username from env, legacy kaggle.json, or the API (access_token tokens)."""
    if os.environ.get("KAGGLE_USERNAME"):
        return os.environ["KAGGLE_USERNAME"]
    home = Path.home() / ".kaggle"
    if (home / "kaggle.json").exists():
        return json.loads((home / "kaggle.json").read_text())["username"]
    if not ((home / "access_token").exists() or os.environ.get("KAGGLE_API_TOKEN")):
        raise SystemExit("No Kaggle credentials: save your API token to ~/.kaggle/access_token "
                         "(kaggle.com > Settings > API)")
    from kaggle.api.kaggle_api_extended import KaggleApi
    api = KaggleApi()
    api.authenticate()
    name = api.get_config_value("username")
    if not name:
        raise SystemExit("Authenticated, but Kaggle did not report a username; set KAGGLE_USERNAME")
    return name


def _link(src, dst):
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists():
        dst.unlink()
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def _job(a):
    """(kernel slug, dataset keys, notebook command, synced dirs) for this job."""
    if getattr(a, "probe24", False):
        return PROBE24_KERNEL_SLUG, ["weights", "code"], ["scripts/probe24_kaggle.py"], ["reports/probe24"]
    if getattr(a, "letters", False):
        slug = LETTERS_KERNEL_SLUG + (f"-{a.tag}" if getattr(a, "tag", "") else "")   # one notebook per tag: runs can overlap
        return (slug, ["weights", "code"],
                ["scripts/letters_kaggle.py", "--nz", "400", "--width", "1000"]
                + (["--assist-every", str(a.assist)] if getattr(a, "assist", 0) else [])
                + (["--shift-curve"] if getattr(a, "shift", False) else [])
                + (["--sigmas", *map(str, a.sigmas)] if getattr(a, "sigmas", None) else [])
                + (["--tag", a.tag] if getattr(a, "tag", "") else []), ["reports/letters"])
    if getattr(a, "ink_gp", False):
        if getattr(a, "full_page", False):
            return INK_GP_KERNEL_SLUG, ["code"], ["scripts/ink_gp_kaggle.py", "--full"], ["reports/ink_gp_full"]
        return INK_GP_KERNEL_SLUG, ["code"], ["scripts/ink_gp_kaggle.py"], ["reports/ink_gp"]
    if getattr(a, "ink", False):
        return (INK_KERNEL_SLUG, ["code"], ["scripts/ink_kaggle.py", "--tag", "all"],
                ["reports/ink_kaggle"])
    if a.crop:
        meta = json.loads((ROOT / "data" / "cache" / f"crop_{a.crop}" / "crop.json").read_text())
        cx, cy, cz = meta["click_in_crop"]
        window = meta["n"]
        if getattr(a, "click", ""):                 # re-seed: volume x,y,z -> crop pixels
            vx, vy, vz = (int(float(v)) for v in a.click.split(","))
            cx, cy, cz = vx - meta["offset_xy"][0], vy - meta["offset_xy"][1], vz
            if not (0 <= cx < meta["size"] and 0 <= cy < meta["size"]
                    and meta["z0"] <= vz < meta["z0"] + meta["n"]):
                raise SystemExit(f"click {a.click} is outside crop {a.crop}")
            window = meta["z0"] + meta["n"] - vz
        if getattr(a, "window", 0):
            window = a.window
        cmd = ["-m", "src.trace.sam3_tracker", "--slices", "data/cache/scroll1_6100_6200",
               "--click", f"{cx},{cy},{cz}", "--window", str(window), "--crop", "2048",
               "--out", "reports/flatten/curves_crop", "--ckpt", "checkpoints/sam3.1_multiplex.pt",
               "--trim-memory", "--first-frame", "walk"]
        DATASETS["crop"] = (f"unscroll-crop-{a.crop}"[:50], f"Unscroll: crop {a.crop}"[:50])
        return CROP_KERNEL_SLUG, ["crop", "weights", "code"], cmd, ["reports/flatten/curves_crop", "reports/run_*.jsonl"]
    args = LARGE_ARGS if getattr(a, "large", False) else TRACE_ARGS
    return (KERNEL_SLUG, ["slices", "weights", "code"],
            ["scripts/seeded_eval.py", "trace", *args],
            ["reports/seeded_eval/curves*", "reports/seeded_eval/logs*"])


def _meta(folder, key, user):
    slug, title = DATASETS[key]
    (folder / "dataset-metadata.json").write_text(json.dumps(
        {"title": title, "id": f"{user}/{slug}", "licenses": [{"name": "other"}]}, indent=2))


def cmd_stage(a):
    user = username()
    slug, keys, cmd, sync = _job(a)
    if a.crop:
        src = ROOT / "data" / "cache" / f"crop_{a.crop}"
        cr = STAGE / "crop"
        if cr.exists():
            shutil.rmtree(cr)
        for f in sorted(src.glob("*.tif")):
            _link(f, cr / f.name)
        shutil.copy2(src / "crop.json", cr / "crop.json")
        (cr / "README.txt").write_text(
            "Crop of EduceLab-Scrolls Scroll 1 (PHercParis4), volume 20230205180739; offset in crop.json.\n"
            "Cite Parsons et al. (2023), arXiv:2304.02084. Data terms: https://scrollprize.org/data\n")
        _meta(cr, "crop", user)
    sl = STAGE / "slices"
    for z in range(Z0, Z0 + WINDOW):
        _link(SLICES / f"{z:05d}.tif", sl / f"{z:05d}.tif")
    shutil.copy2(SEGS / "volume.meta.json", sl / "volume.meta.json")
    (sl / "README.txt").write_text(
        "EduceLab-Scrolls Scroll 1 (PHercParis4), volume 20230205180739, slices 6100-6119.\n"
        "Cite Parsons et al. (2023), arXiv:2304.02084. Data terms: https://scrollprize.org/data\n"
        "CC BY-NC 4.0 unless otherwise specified. Private copy for the Unscroll evaluation.\n")
    _meta(sl, "slices", user)
    we = STAGE / "weights"
    _link(CKPT, we / CKPT.name)
    shutil.copy2(ROOT / "external" / "sam3" / "LICENSE", we / "SAM_LICENSE.txt")
    _meta(we, "weights", user)
    co = STAGE / "code"
    co.mkdir(parents=True, exist_ok=True)
    with tarfile.open(co / "unscroll_code.tgz.bin", "w:gz") as t:
        for part in CODE_PARTS:
            t.add(ROOT / part, arcname=part,
                  filter=lambda ti: None if "__pycache__" in ti.name else ti)
    _meta(co, "code", user)
    ke = STAGE / f"kernel_{slug}"      # one folder per notebook: jobs may be staged concurrently
    ke.mkdir(parents=True, exist_ok=True)
    (ke / "run.py").write_text(f"CMD = {cmd!r}\nSYNC = {sync!r}\n" + KERNEL.lstrip())
    (ke / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{user}/{slug}", "title": slug, "code_file": "run.py",
        "language": "python", "kernel_type": "script", "is_private": True,
        "enable_gpu": True, "enable_internet": True, "machine_shape": "NvidiaTeslaT4",
        "dataset_sources": [f"{user}/{DATASETS[k][0]}" for k in keys],
        "competition_sources": [INK_COMPETITION] if getattr(a, "ink", False) else [],
        "kernel_sources": []}, indent=2))
    size = sum(f.stat().st_size for f in STAGE.rglob("*") if f.is_file())
    print(f"staged {size / 1e9:.2f} GB in {STAGE} for user {user}")


def cmd_push_data(a):
    user = username()
    keys = a.only or _job(a)[1]
    _job(a)
    for key in keys:
        folder, slug = STAGE / key, DATASETS[key][0]
        exists = kaggle("datasets", "status", f"{user}/{slug}", check=False).returncode == 0
        if exists:
            kaggle("datasets", "version", "-p", str(folder), "-m", "update", "-r", "skip")
        else:  # create is private unless --public is given
            kaggle("datasets", "create", "-p", str(folder), "-r", "skip")


def cmd_push_kernel(a):
    kaggle("kernels", "push", "-p", str(STAGE / f"kernel_{_job(a)[0]}"))


def cmd_status(a):
    kaggle("kernels", "status", f"{username()}/{_job(a)[0]}", check=False)


def cmd_fetch(a):
    slug = _job(a)[0]
    dest = ROOT / "kaggle" / "output" / slug      # per notebook: fetches may overlap
    if dest.exists():
        shutil.rmtree(dest)
    # curves, logs and json (plus ink PNGs); never frames3/*.jpg or model weights
    ink_job = any(getattr(a, k, False) for k in ("ink", "ink_gp", "letters", "probe24"))
    pattern = r".*\.(jsonl|log|json|png)$" if ink_job else r".*\.(jsonl|log|json)$"
    for attempt in range(3):
        if kaggle("kernels", "output", f"{username()}/{slug}", "-p", str(dest), "-q",
                  "--file-pattern", pattern, check=False).returncode == 0:
            break
        print(f"download attempt {attempt + 1} failed; retrying", flush=True)
    src = dest / "out"
    if getattr(a, "probe24", False):
        shutil.copytree(src / "probe24", ROOT / "reports" / "probe24", dirs_exist_ok=True)
        print("probe24 results:", sorted(p.name for p in (ROOT / "reports" / "probe24").iterdir()))
        return
    if getattr(a, "letters", False):
        shutil.copytree(src / "letters", ROOT / "reports" / "letters", dirs_exist_ok=True)
        print("letters results:", sorted(p.name for p in (ROOT / "reports" / "letters").iterdir()))
        return
    if getattr(a, "ink_gp", False) and getattr(a, "full_page", False):
        shutil.copytree(src / "ink_gp_full", ROOT / "reports" / "ink_gp_full", dirs_exist_ok=True)
        print("ink_gp_full results:", sorted(p.name for p in (ROOT / "reports" / "ink_gp_full").iterdir()))
        return
    if getattr(a, "ink_gp", False):
        shutil.copytree(src / "ink_gp", ROOT / "reports" / "ink_gp", dirs_exist_ok=True)
        print("ink_gp results:", sorted(p.name for p in (ROOT / "reports" / "ink_gp").iterdir()))
        return
    if getattr(a, "ink", False):
        shutil.copytree(src / "ink_kaggle", ROOT / "reports" / "ink_kaggle", dirs_exist_ok=True)
        print("ink results:", sorted(p.name for p in (ROOT / "reports" / "ink_kaggle").iterdir()))
        return
    if a.crop:
        from scripts.make_crop import shift_curves
        meta = json.loads((ROOT / "data" / "cache" / f"crop_{a.crop}" / "crop.json").read_text())
        tag = getattr(a, "tag", "") or "kaggle"
        out = ROOT / "reports" / "flatten" / f"curves_{a.crop}_{tag}"
        logs = ROOT / "reports" / "flatten" / f"runlogs_{a.crop}_{tag}"
        logs.mkdir(parents=True, exist_ok=True)
        for f in src.glob("run_*.jsonl"):
            shutil.copy2(f, logs / f.name)
        if out.exists():
            shutil.rmtree(out)
        shift_curves(src / "curves_crop", out, meta["offset_xy"])
        print("volume-coordinate curves:", out, len(list(out.glob("*.jsonl"))))
        return
    for sub in [*src.glob("curves*"), *src.glob("logs*")]:
        shutil.copytree(sub, ROOT / "reports" / "seeded_eval" / sub.name, dirs_exist_ok=True)
    print("fetched:", sorted(p.name for p in src.iterdir()) if src.is_dir() else "nothing")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("step", choices=["stage", "push-data", "push-kernel", "status", "fetch"])
    ap.add_argument("--only", nargs="*", choices=[*DATASETS, "crop"])
    ap.add_argument("--crop", default="", help="seed id of a make_crop.py stack (crop job)")
    ap.add_argument("--probe24", action="store_true", help="tracer on the 2.4 um Scroll 1 scan (open data bucket)")
    ap.add_argument("--large", action="store_true", help="tracing job on the large held-out click set")
    ap.add_argument("--ink", action="store_true", help="ink-training job on the 2023 competition fragments")
    ap.add_argument("--ink-gp", action="store_true", help="Grand Prize ink model: known segment + our surface")
    ap.add_argument("--full-page", action="store_true", help="with --ink-gp: the whole segment, every column")
    ap.add_argument("--letters", action="store_true", help="letter-scale demo: trace a known-text sheet and read it")
    ap.add_argument("--sigmas", type=float, nargs="+", help="letters: slice smoothing strengths for our trace")
    ap.add_argument("--shift", action="store_true", help="letters: ink vs surface offset curve only")
    ap.add_argument("--assist", type=int, default=0, help="letters: one simulated scholar click every N slices")
    ap.add_argument("--click", default="", help="crop job: re-seed click x,y,z in volume coordinates")
    ap.add_argument("--window", type=int, default=0, help="crop job: slices to trace")
    ap.add_argument("--tag", default="", help="crop job: output name suffix (default kaggle); letters: output folder and notebook suffix")
    a = ap.parse_args(argv)
    {"stage": cmd_stage, "push-data": cmd_push_data, "push-kernel": cmd_push_kernel,
     "status": cmd_status, "fetch": cmd_fetch}[a.step](a)
    return 0


if __name__ == "__main__":
    sys.exit(main())
