CKPT = ROOT / "checkpoints" / "sam3.1_multiplex.pt"
Z0, WINDOW = 6100, 20
DATASETS = {
    "slices": ("unscroll-scroll1-slices", "Unscroll: Scroll 1 CT slices 6100-6119"),
    "weights": ("unscroll-sam31-weights", "Unscroll: SAM 3.1 checkpoint (SAM License)"),
    "code": ("unscroll-code", "Unscroll: tracing code and seeds"),
}
assert all(6 <= len(t) <= 50 for _, t in DATASETS.values()), "Kaggle titles: 6-50 chars"
KERNEL_SLUG = "unscroll-seeded-trace"
