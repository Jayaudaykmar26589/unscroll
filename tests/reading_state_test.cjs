const assert=require('node:assert/strict'),fs=require('node:fs'),R=require('../viewer/reading-state.js');
const b=JSON.parse(fs.readFileSync('data/reading/passage.json','utf8'));
b.bundle_id='unit-test-source';b.source_text=b.lines.map(l=>l.text).join('\n');
let s=R.create(b);const original=JSON.stringify(b);
assert(R.current(b,s,'en')&&R.current(b,s,'ta'));
R.edit(b,s,'l11','οὐ? ἤδη τὰ σπάνια');
assert(!R.current(b,s,'en')&&!R.current(b,s,'ta'),'Greek correction must stale BOTH translations');
assert.equal(JSON.stringify(b),original,'Published source must remain immutable');
R.humanTranslation(b,s,'en','An edited English draft');
assert(R.current(b,s,'en')&&!R.current(b,s,'ta'),'Reviewing one language must not validate the other');
const exported=R.exportReview(b,s);assert.equal(exported.translations.ta.current,false);assert.equal(exported.corrected_lines[1].changed,true);
assert.equal(exported.published_lines[1].text,b.lines[1].text);
const snapshot=R.source(b,s),revision=s.revision;
R.edit(b,s,'l10','ἐπὶ τῶν βρωμάτων?');
assert.equal(R.modelResult(b,s,revision,snapshot,{translations:{en:'old',ta:'பழைய'}}),false,'Late response must not overwrite a newer reading');
const now=R.source(b,s),rev=s.revision;
R.humanTranslation(b,s,'ta','மனிதர் திருத்திய வரைவு');
assert.equal(R.modelResult(b,s,rev,now,{translations:{en:'old',ta:'பழைய'}}),false,'Late response must not overwrite human translation edits');
assert.deepEqual(R.restore(b,JSON.parse(JSON.stringify(s))),s,'Corrections survive reload');
assert.equal(R.restore({...b,bundle_id:'different-source'},s).revision,0,'Different source must not inherit corrections');
assert.equal(R.restore(b,{bundle_id:b.bundle_id,revision:1,history:[],lines:{}}).revision,0,'Corrupt local storage must recover');
assert.equal(R.norm('α\u0301\r\nβ'),'ά\nβ');
assert.throws(()=>R.edit(b,s,'missing','x'));
console.log('Reading state: stale translations, Unicode, provenance, concurrency, persistence and corruption checks passed');
const pred={image_sha256:b.source.image_sha256,run_id:'test-run',model:'test',lines:b.lines.map(l=>({id:l.id,bbox:l.bbox,text:'?'}))};
const originalReading=R.source(b,s);R.recognitionResult(b,s,pred);
assert.equal(R.source(b,s),originalReading,'Receiving predictions never changes human corrections');
R.acceptPrediction(b,s,'l10');assert.equal(s.lines.l10,'?');
assert.equal(s.history.at(-1).type,'recognition_accept');
assert(!R.current(b,s,'en')&&!R.current(b,s,'ta'));
R.edit(b,s,'l10','λόγος');assert.equal(s.recognition.lines[0].text,'?','Correction must retain original model prediction');
assert.equal(R.exportReview(b,s).recognition.run_id,'test-run');
assert.deepEqual(R.restore(b,JSON.parse(JSON.stringify(s))).recognition,s.recognition);
assert.throws(()=>R.recognitionResult(b,s,{...pred,image_sha256:'wrong'}));
assert.throws(()=>R.recognitionResult(b,s,{...pred,lines:[pred.lines[0],...pred.lines.slice(0,4)]}));
assert.throws(()=>R.recognitionResult(b,s,{...pred,lines:pred.lines.map(l=>({...l,bbox:[0,0,1,1]}))}));
console.log('Recognition provenance, region alignment, explicit acceptance and stale translation tests passed');
